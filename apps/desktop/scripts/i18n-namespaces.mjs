import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';

const LOCALES = ['zh-CN', 'en', 'ja', 'ko', 'zh-TW', 'fr', 'de', 'es', 'pt', 'ru'];
const LOCALE_EXPORTS = {
  'zh-CN': 'zhCN',
  en: 'en',
  ja: 'ja',
  ko: 'ko',
  'zh-TW': 'zhTW',
  fr: 'fr',
  de: 'de',
  es: 'es',
  pt: 'pt',
  ru: 'ru',
};
const BASE_LOCALE = 'en';
const root = process.cwd();
const i18nDir = path.join(root, 'src', 'i18n');
const localesDir = path.join(i18nDir, 'locales');
const generatedHeader = '// Generated by scripts/i18n-namespaces.mjs. Do not edit by hand.\n';

function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, 'utf8'));
}

function writeIfChanged(filePath, content) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  if (fs.existsSync(filePath) && fs.readFileSync(filePath, 'utf8') === content) {
    return false;
  }
  fs.writeFileSync(filePath, content, 'utf8');
  return true;
}

function listNamespaceFiles(locale) {
  const localeDir = path.join(localesDir, locale);
  if (!fs.existsSync(localeDir)) {
    return [];
  }
  return fs
    .readdirSync(localeDir)
    .filter((name) => name.endsWith('.json'))
    .map((name) => name.slice(0, -'.json'.length))
    .sort((a, b) => a.localeCompare(b));
}

function validateNamespaceObject(locale, namespace, value, errors) {
  if (!value || typeof value !== 'object' || Array.isArray(value)) {
    errors.push(`${locale}/${namespace}.json must contain an object`);
    return;
  }

  for (const [key, text] of Object.entries(value)) {
    if (!key || key.includes('\n')) {
      errors.push(`${locale}/${namespace}.json has an invalid key: ${JSON.stringify(key)}`);
    }
    if (typeof text !== 'string') {
      errors.push(`${locale}/${namespace}.json:${key} must be a string`);
    }
  }
}

function loadLocaleNamespaces(locale, namespaceNames, errors) {
  const namespaces = new Map();

  for (const namespace of namespaceNames) {
    const filePath = path.join(localesDir, locale, `${namespace}.json`);
    if (!fs.existsSync(filePath)) {
      errors.push(`${locale} is missing namespace ${namespace}.json`);
      continue;
    }
    const messages = readJson(filePath);
    validateNamespaceObject(locale, namespace, messages, errors);
    namespaces.set(namespace, messages);
  }

  return namespaces;
}

function compareLocaleToBase(locale, baseNamespaces, namespaceNames, errors) {
  const namespaceFiles = listNamespaceFiles(locale);
  const missingFiles = namespaceNames.filter((namespace) => !namespaceFiles.includes(namespace));
  const extraFiles = namespaceFiles.filter((namespace) => !namespaceNames.includes(namespace));

  for (const namespace of missingFiles) {
    errors.push(`${locale} is missing namespace file ${namespace}.json`);
  }
  for (const namespace of extraFiles) {
    errors.push(`${locale} has extra namespace file ${namespace}.json`);
  }

  const localeNamespaces = loadLocaleNamespaces(locale, namespaceNames, errors);
  for (const namespace of namespaceNames) {
    const baseMessages = baseNamespaces.get(namespace) ?? {};
    const messages = localeNamespaces.get(namespace);
    if (!messages) continue;

    const baseKeys = Object.keys(baseMessages).sort();
    const localeKeys = Object.keys(messages).sort();
    for (const key of baseKeys.filter((candidate) => !localeKeys.includes(candidate))) {
      errors.push(`${locale}/${namespace}.json is missing key ${key}`);
    }
    for (const key of localeKeys.filter((candidate) => !baseKeys.includes(candidate))) {
      errors.push(`${locale}/${namespace}.json has extra key ${key}`);
    }
  }
}

function renderTypes(namespaceNames) {
  const imports = namespaceNames
    .map((namespace) => `import type ${namespace} from './locales/${BASE_LOCALE}/${namespace}.json';`)
    .join('\n');
  const locales = LOCALES.map((locale) => `  '${locale}',`).join('\n');
  const namespaces = namespaceNames.map((namespace) => `  '${namespace}',`).join('\n');
  const keyMap = namespaceNames.map((namespace) => `  ${namespace}: typeof ${namespace};`).join('\n');

  return `${generatedHeader}${imports}\n\nexport const locales = [\n${locales}\n] as const;\n\nexport type Locale = (typeof locales)[number];\n\nexport const translationNamespaces = [\n${namespaces}\n] as const;\n\nexport type TranslationNamespace = (typeof translationNamespaces)[number];\n\ntype NamespaceKeyMap = {\n${keyMap}\n};\n\ntype NamespacedKey<Namespace extends string, Key extends string> = \`${'${Namespace}'}.${'${Key}'}\`;\n\nexport type TranslationKey = {\n  [Namespace in keyof NamespaceKeyMap]: NamespacedKey<\n    Extract<Namespace, string>,\n    Extract<keyof NamespaceKeyMap[Namespace], string>\n  >;\n}[keyof NamespaceKeyMap];\n\nexport type TranslationKeys = Record<TranslationKey, string>;\n`;
}

function renderLocaleIndex(locale, namespaceNames) {
  const exportName = LOCALE_EXPORTS[locale];
  const imports = namespaceNames
    .map((namespace) => `import ${namespace} from './${namespace}.json';`)
    .join('\n');
  const namespaceEntries = namespaceNames.map((namespace) => `  ${namespace},`).join('\n');

  return `${generatedHeader}import { flattenTranslationNamespaces } from '../../namespace';\nimport type { TranslationKeys } from '../../types';\n${imports}\n\nexport const ${exportName}: TranslationKeys = flattenTranslationNamespaces({\n${namespaceEntries}\n});\n`;
}

function expectedGeneratedFiles(namespaceNames) {
  const files = new Map();
  files.set(path.join(i18nDir, 'types.ts'), renderTypes(namespaceNames));
  for (const locale of LOCALES) {
    files.set(path.join(localesDir, locale, 'index.ts'), renderLocaleIndex(locale, namespaceNames));
  }
  return files;
}

function collectValidation() {
  const errors = [];
  const namespaceNames = listNamespaceFiles(BASE_LOCALE);
  if (namespaceNames.length === 0) {
    errors.push(`Base locale ${BASE_LOCALE} has no namespace JSON files`);
  }

  const baseNamespaces = loadLocaleNamespaces(BASE_LOCALE, namespaceNames, errors);
  for (const locale of LOCALES) {
    compareLocaleToBase(locale, baseNamespaces, namespaceNames, errors);
  }

  return { errors, namespaceNames };
}

function checkGeneratedFiles(namespaceNames, errors) {
  for (const [filePath, expected] of expectedGeneratedFiles(namespaceNames)) {
    if (!fs.existsSync(filePath)) {
      errors.push(`${path.relative(root, filePath)} is missing; run npm run i18n:generate`);
      continue;
    }
    const actual = fs.readFileSync(filePath, 'utf8');
    if (actual !== expected) {
      errors.push(`${path.relative(root, filePath)} is stale; run npm run i18n:generate`);
    }
  }
}

function generate(namespaceNames) {
  let changed = 0;
  for (const [filePath, content] of expectedGeneratedFiles(namespaceNames)) {
    if (writeIfChanged(filePath, content)) {
      changed += 1;
    }
  }
  console.log(`i18n generated ${changed} file${changed === 1 ? '' : 's'}`);
}

const command = process.argv[2] ?? 'check';
const { errors, namespaceNames } = collectValidation();

if (command === 'generate') {
  if (errors.length > 0) {
    console.error(errors.join('\n'));
    process.exit(1);
  }
  generate(namespaceNames);
} else if (command === 'check') {
  checkGeneratedFiles(namespaceNames, errors);
  if (errors.length > 0) {
    console.error(errors.join('\n'));
    process.exit(1);
  }
  console.log('i18n namespaces ok');
} else {
  console.error(`Unknown command: ${command}`);
  process.exit(1);
}
